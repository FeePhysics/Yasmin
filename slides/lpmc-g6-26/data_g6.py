def count_wall(R, C, widths):
    cnt = 0
    def place(i, used):
        nonlocal cnt
        if i == len(widths): cnt += 1; return
        w = widths[i]
        for r in range(R):
            for c in range(C - w + 1):
                cs = {(r, c + k) for k in range(w)}
                if not cs & used: place(i + 1, used | cs)
    place(0, set()); return cnt
