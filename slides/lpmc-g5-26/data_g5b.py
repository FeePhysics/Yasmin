def best_pay(items, coupons):
    n = len(items); best = None; plan = None
    for assign in itertools.product(range(n), repeat=n):
        groups = {}
        for it, g in zip(items, assign): groups.setdefault(g, []).append(it)
        gl = list(groups.values())
        for cs in itertools.permutations(list(range(len(coupons))) + [None] * len(gl), len(gl)):
            tot = sum(sum(g) if c is None else sum(g) - coupons[c][0](sum(g)) for g, c in zip(gl, cs))
            if best is None or tot < best: best, plan = tot, list(zip(gl, cs))
    return best, plan
