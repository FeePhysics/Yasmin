    P_ = [(x, y) for x in range(C) for y in range(R)]; S_ = set(P_); out = set(); upright = 0
    for a in P_:
        for b in P_:
            if a == b: continue
            dx, dy = b[0] - a[0], b[1] - a[1]; c = (b[0] - dy, b[1] + dx); e = (a[0] - dy, a[1] + dx)
            if c in S_ and e in S_: out.add(frozenset([a, b, c, e]))
    up = sum(1 for s in out if len({p[0] for p in s}) == 2)
    return len(out), up
