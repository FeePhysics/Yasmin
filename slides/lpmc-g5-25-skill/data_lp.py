def item28(a, b, total, fa, fb):
    fa, fb = F(fa), F(fb); sols = [x for x in range(1, total) if fa * x == fb * (total - x)]; assert len(sols) == 1
    x = sols[0]; y = total - x; r = fb / fa  # x : y = fb : fa
    ra, rb = (fb / math.gcd(fb.numerator * fa.denominator, fa.numerator * fb.denominator)), None
    pa, pb = (fb.numerator * fa.denominator), (fa.numerator * fb.denominator); g = math.gcd(pa, pb); pa //= g; pb //= g
    u = total // (pa + pb)
    q = f"{a}และ{b}มีเงินรวมกัน {total} บาท ถ้า {ffr(fa)} ของเงิน{a}เท่ากับ {ffr(fb)} ของเงิน{b} อยากทราบว่า{a}และ{b}มีเงินต่างกันกี่บาท"
    st = [f"{ffr(fa)} × {a} = {ffr(fb)} × {b} → {a} : {b} = {pa} : {pb}", f"รวม {pa + pb} ส่วน = {total} → 1 ส่วน = {u}", f"{a} {x} บาท · {b} {y} บาท", f"ต่างกัน = {max(x, y)} − {min(x, y)} = {abs(x - y)}"]
    return I(q, st, abs(x - y), f"ตรวจ: {ffr(fa)} × {x} = {ffr(fa * x)} และ {ffr(fb)} × {y} = {ffr(fb * y)} เท่ากัน ✓")
